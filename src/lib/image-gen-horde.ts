export interface HordeHealth {
  provider: "ai-horde";
  configured: boolean;
  anonymous: boolean;
  reachable: boolean;
  model: string;
  modelWorkers: number | null;
  queueEtaSeconds: number | null;
  note: string;
}

let healthCache: { at: number; value: HordeHealth | null } = { at: 0, value: null };

/** Last safe failure category, for admin diagnostics (no prompt content). */
let lastErrorCategory: FailureCategory | null = null;
export function lastImageErrorCategory(): FailureCategory | null {
  return lastErrorCategory;
}
export function noteImageError(c: FailureCategory): void {
  lastErrorCategory = c;
}

export async function hordeHealth(): Promise<HordeHealth> {
  if (healthCache.value && Date.now() - healthCache.at < 60_000) return healthCache.value;
  const model = hordeModel();
  const base: HordeHealth = {
    provider: "ai-horde",
    configured: true,
    anonymous: usingAnonymousKey(),
    reachable: false,
    model,
    modelWorkers: null,
    queueEtaSeconds: null,
    note: usingAnonymousKey()
      ? "Using the shared anonymous key — free but lowest queue priority. Set AI_HORDE_API_KEY for faster generations."
      : "Using a personal AI Horde key.",
  };
  try {
    const models = await hordeFetch<{ name?: string; count?: number; eta?: number }[]>(
      "/status/models?type=image",
      { timeoutMs: 10_000 }
    );
    const entry = models.find((m) => m.name === model);
    healthCache = {
      at: Date.now(),
      value: {
        ...base,
        reachable: true,
        modelWorkers: entry?.count ?? 0,
        queueEtaSeconds: entry?.eta ?? null,
        note:
          entry === undefined
            ? `Model "${model}" is not currently served by any worker — set AI_HORDE_MODEL to an available one.`
            : base.note,
      },
    };
  } catch {
    healthCache = { at: Date.now(), value: base };
  }
  return healthCache.value!;
}
